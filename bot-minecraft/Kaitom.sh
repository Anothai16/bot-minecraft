#!/bin/bash
cd "$(dirname "$0")"

chmod +x ./MinecraftClient

# เปิดการตรวจจับ Exit Code ของโปรแกรมฝั่งขวาใน Pipeline
set -o pipefail

(
  # ==========================================
  # 🔑 1. รอหน้า Dialog โหลดขึ้นมา แล้วล็อกอิน
  # ==========================================
  echo "[LOGIN] กำลังรอหน้า Dialog โหลด..." >&2
  sleep 10
  echo "/dialog input pass 112233"
  
  sleep 3
  echo "/dialog click 1"
  echo "[LOGIN] ปลดล็อกหน้าต่าง Dialog เรียบร้อย" >&2
  
  # ==========================================
  # 🧭 2. รอปลดล็อกล็อกอิน แล้วสั่งกดใช้เข็มทิศ
  # ==========================================
  echo "[LOBBY] กำลังรอวาร์ปเข้าจุด Spawn..." >&2
  sleep 10
  echo "/useitem mainhand"
  
  # ==========================================
  # 📦 3. จิ้มเลือกสล็อต 10 (Survival)
  # ==========================================
  sleep 1
  echo "/inventory container click 10 Left"
  echo "[LOBBY] เลือก Survival เรียบร้อย กำลังสลับโลก..." >&2
  
  # ==========================================
  # 🏠 4. รอโหลดเข้าโลก แล้ววาร์ปมาหน้าคันโยก
  # ==========================================
  sleep 8
  echo "/home home"
  echo "[READY] บอท Kaitom_4 ประจำการที่จุดคันโยกเรียบร้อย!" >&2

  # ==========================================
  # ⏰ 5. ลูปตรวจสอบเวลาสับคันโยก (05:50 และ 07:30 น.)
  # ==========================================
  TRIGGERED_0550=false
  TRIGGERED_0730=false

  while true; do
    HOUR=$(date +%-H)
    MIN=$(date +%-M)

    # 🔄 รีเซ็ต Flag รายวันช่วงเที่ยงคืน
    if [ "$HOUR" -eq 0 ] && [ "$MIN" -eq 0 ]; then
      TRIGGERED_0550=false
      TRIGGERED_0730=false
    fi

    # 🔴 1. เวลา 05:50 น. -> สับคันโยกครั้งที่ 1 (ปิดระบบ)
    if [ "$HOUR" -eq 5 ] && [ "$MIN" -eq 50 ] && [ "$TRIGGERED_0550" = false ]; then
      NOW_TIME=$(date '+%H:%M:%S')
      echo "==================================================" >&2
      echo "🛑 [LEVER $NOW_TIME] ถึงเวลา 05:50 น. สั่งสับคันโยก (ปิดระบบ)..." >&2
      echo "/useblock 10383 64.00 -5064.51"
      echo "==================================================" >&2
      TRIGGERED_0550=true
    fi

    # 🔄 2. เวลา 07:20 น. -> สั่งออกจากเซิร์ฟเวอร์เพื่อรีเซ็ตโปรเซสผ่าน PM2 ก่อนเริ่มงานใหม่
    if [ "$HOUR" -eq 7 ] && [ "$MIN" -eq 10 ]; then
      NOW_TIME=$(date '+%H:%M:%S')
      echo "🔄 [RESTART $NOW_TIME] ถึงเวลา 07:10 น. สั่งปิดบอทเพื่อให้ PM2 รีสตาร์ตระบบใหม่..." >&2
      echo "/quit"
      exit 0
    fi

    # 🟢 3. เวลา 07:30 น. -> สับคันโยกครั้งที่ 2 (เปิดระบบ)
    if [ "$HOUR" -eq 7 ] && [ "$MIN" -eq 30 ] && [ "$TRIGGERED_0730" = false ]; then
      NOW_TIME=$(date '+%H:%M:%S')
      echo "==================================================" >&2
      echo "🟢 [LEVER $NOW_TIME] ถึงเวลา 07:30 น. สั่งสับคันโยก (เปิดระบบ)..." >&2
      echo "/useblock 10383 64.00 -5064.51"
      echo "==================================================" >&2
      TRIGGERED_0730=true
    fi

    # ส่งบรรทัดว่างเบาๆ เพื่อตรวจเช็คการเชื่อมต่อ
    echo ""
    sleep 5
  done
) | ./MinecraftClient Kaitom_4 - play.amorycraft.com

# ==========================================
# 🛑 เช็คสถานะการทำงาน: ถ้าหลุด/เข้าเซิร์ฟไม่ได้ ให้จบด้วย Error (PM2 จะรีสตาร์ตทันที)
# ==========================================
EXIT_STATUS=$?
if [ $EXIT_STATUS -ne 0 ]; then
  echo "⚠️ [ERROR] บอทหลุดการเชื่อมต่อหรือเกิดข้อผิดพลาด (Exit Code: $EXIT_STATUS) สั่งรีสตาร์ตผ่าน PM2..." >&2
  exit 1
fi